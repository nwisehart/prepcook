//! `prepcook up`, `prepcook down` and `prepcook status`: the board stack (Postgres,
//! ElectricSQL and the remote server) run with Docker Compose from files kept
//! in `<app data dir>/board`, so a downloaded binary needs no checkout.

use std::{
    ffi::OsString,
    io::Write,
    path::{Path, PathBuf},
    time::{Duration, Instant},
};

use base64::{
    Engine,
    engine::general_purpose::{STANDARD, URL_SAFE_NO_PAD},
};
use rand::RngCore;
use services::services::board_secret::{self, BOARD_SECRET_NAME, LOCAL_BOARD_URL};
use utils::{assets::asset_dir, port_file::read_port_info};

use super::{DownOptions, UpOptions};

/// The board's published port on this machine (`REMOTE_SERVER_PORTS` in the
/// compose file).
pub const BOARD_URL: &str = LOCAL_BOARD_URL;

/// How long `prepcook up` waits for the board's health endpoint.
const HEALTH_TIMEOUT: Duration = Duration::from_secs(120);

/// The compose project name, shared by `up`, `down` and `status` so they all
/// address the same containers and volumes whichever compose file started
/// them.
const PROJECT: &str = "prepcook";

const RELEASE_COMPOSE: &str = include_str!("../../../remote/docker-compose.release.yml");
const BOARD_IMAGE_LATEST: &str = "ghcr.io/nwisehart/prepcook-board:latest";
const BOARD_IMAGE: &str = "ghcr.io/nwisehart/prepcook-board";

pub fn board_dir() -> PathBuf {
    asset_dir().join("board")
}

/// The embedded release compose file with the board image pinned to this
/// binary's version.
pub fn release_compose() -> String {
    RELEASE_COMPOSE.replace(
        BOARD_IMAGE_LATEST,
        &format!("{BOARD_IMAGE}:{}", env!("CARGO_PKG_VERSION")),
    )
}

/// A random 32-byte value, base64 without padding in the URL-safe alphabet:
/// the database passwords are interpolated into connection URLs, where `/`,
/// `+` and `=` would break parsing.
fn url_safe_secret() -> String {
    URL_SAFE_NO_PAD.encode(random_bytes())
}

fn random_bytes() -> [u8; 32] {
    let mut bytes = [0u8; 32];
    rand::rngs::OsRng.fill_bytes(&mut bytes);
    bytes
}

/// The contents of a new board `.env`. `PREPCOOK_JWT_SECRET` is also the
/// server's board secret: the server signs its requests to the board with it.
pub fn generate_env() -> String {
    format!(
        "# Generated by `prepcook up`. Keep this file private: it holds the board's\n\
         # database passwords and its token-signing secret, which Prep Cook signs\n\
         # its requests to the board with.\n\
         DB_PASSWORD={db}\n\
         ELECTRIC_ROLE_PASSWORD={electric}\n\
         # The board decodes this as standard base64 and needs at least 32 bytes.\n\
         PREPCOOK_JWT_SECRET={jwt}\n\
         PUBLIC_BASE_URL=http://localhost:4110\n",
        db = url_safe_secret(),
        electric = url_safe_secret(),
        jwt = STANDARD.encode(random_bytes()),
    )
}

/// Creates the `.env` at `path` (mode 0600) unless it exists. Returns whether
/// the file was created.
pub fn ensure_env_file(path: &Path) -> std::io::Result<bool> {
    let contents = generate_env();
    let mut options = std::fs::OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(0o600);
    }
    let mut file = match options.open(path) {
        Ok(file) => file,
        Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => return Ok(false),
        Err(e) => return Err(e),
    };
    file.write_all(contents.as_bytes())?;
    file.sync_all()?;
    Ok(true)
}

/// How Compose is invoked on this machine.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ComposeTool {
    /// `docker compose` (the Compose v2 plugin).
    Plugin,
    /// `docker-compose` (the standalone binary).
    Standalone,
}

impl ComposeTool {
    fn program(self) -> &'static str {
        match self {
            ComposeTool::Plugin => "docker",
            ComposeTool::Standalone => "docker-compose",
        }
    }
}

/// The arguments after the program for a compose command on the prepcook project.
pub fn compose_args(
    tool: ComposeTool,
    env_file: &Path,
    compose_file: &Path,
    command: &[&str],
) -> Vec<OsString> {
    let mut args: Vec<OsString> = Vec::new();
    if tool == ComposeTool::Plugin {
        args.push("compose".into());
    }
    args.push("--project-name".into());
    args.push(PROJECT.into());
    args.push("--env-file".into());
    args.push(env_file.into());
    args.push("-f".into());
    args.push(compose_file.into());
    args.extend(command.iter().map(OsString::from));
    args
}

async fn succeeds(program: &str, args: &[&str]) -> Option<bool> {
    match tokio::process::Command::new(program)
        .args(args)
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status()
        .await
    {
        Ok(status) => Some(status.success()),
        Err(_) => None,
    }
}

async fn detect_compose() -> Result<ComposeTool, String> {
    let docker = succeeds("docker", &["--version"]).await;
    if docker == Some(true) && succeeds("docker", &["compose", "version"]).await == Some(true) {
        return Ok(ComposeTool::Plugin);
    }
    if succeeds("docker-compose", &["version"]).await == Some(true) {
        return Ok(ComposeTool::Standalone);
    }
    if docker.is_none() {
        Err("Docker is required for the board: install Docker Desktop or Docker Engine (https://docs.docker.com/get-docker/) and run prepcook up again.".to_string())
    } else {
        Err("Docker is installed but Compose is not: install the Compose plugin (https://docs.docker.com/compose/install/) and run prepcook up again.".to_string())
    }
}

async fn run_compose(
    tool: ComposeTool,
    env_file: &Path,
    compose_file: &Path,
    command: &[&str],
) -> Result<(), String> {
    let args = compose_args(tool, env_file, compose_file, command);
    let status = tokio::process::Command::new(tool.program())
        .args(&args)
        .status()
        .await
        .map_err(|e| format!("could not run {}: {e}", tool.program()))?;
    if status.success() {
        Ok(())
    } else {
        Err(format!(
            "{} {} failed ({status})",
            tool.program(),
            args.iter()
                .map(|a| a.to_string_lossy())
                .collect::<Vec<_>>()
                .join(" ")
        ))
    }
}

/// Writes the embedded compose file into the board directory unless a
/// compose file was given, and returns the one to use.
fn compose_file(board: &Path, given: Option<&PathBuf>) -> std::io::Result<PathBuf> {
    if let Some(path) = given {
        return Ok(path.clone());
    }
    let path = board.join("docker-compose.yml");
    std::fs::write(&path, release_compose())?;
    Ok(path)
}

async fn answers(client: &reqwest::Client, url: &str) -> bool {
    matches!(client.get(url).send().await, Ok(response) if response.status().is_success())
}

fn http_client() -> reqwest::Client {
    reqwest::Client::builder()
        .timeout(Duration::from_secs(2))
        .build()
        .expect("an HTTP client with a timeout always builds")
}

async fn wait_for_board() -> Result<(), String> {
    let client = http_client();
    let url = format!("{BOARD_URL}/v1/health");
    let started = Instant::now();
    loop {
        if answers(&client, &url).await {
            eprintln!("\rthe board is up at {BOARD_URL}                    ");
            return Ok(());
        }
        let waited = started.elapsed();
        if waited >= HEALTH_TIMEOUT {
            eprintln!();
            return Err(format!(
                "the board did not answer at {url} within {} s; `docker compose --project-name {PROJECT} logs remote-server` shows why",
                HEALTH_TIMEOUT.as_secs()
            ));
        }
        eprint!(
            "\rwaiting for the board at {BOARD_URL} ... {}s",
            waited.as_secs()
        );
        let _ = std::io::stderr().flush();
        tokio::time::sleep(Duration::from_secs(1)).await;
    }
}

/// Starts the board and waits for it to answer. The caller then starts the
/// server unless `--board-only` was given.
pub async fn up(options: &UpOptions) -> Result<(), String> {
    // Before anything is written, so a machine without Docker is left
    // untouched.
    let tool = detect_compose().await?;
    let board = board_dir();
    std::fs::create_dir_all(&board)
        .map_err(|e| format!("could not create {}: {e}", board.display()))?;
    let compose = compose_file(&board, options.compose.as_ref())
        .map_err(|e| format!("could not write the board's compose file: {e}"))?;
    let env_file = board.join(".env");
    match ensure_env_file(&env_file) {
        Ok(true) => println!(
            "{} holds the board's generated passwords and secret; keep it private.",
            env_file.display()
        ),
        Ok(false) => {}
        Err(e) => return Err(format!("could not write {}: {e}", env_file.display())),
    }

    run_compose(tool, &env_file, &compose, &["up", "-d"]).await?;
    wait_for_board().await
}

pub async fn down(options: &DownOptions) -> Result<(), String> {
    let board = board_dir();
    let env_file = board.join(".env");
    if !env_file.exists() {
        println!("No board to stop: {} does not exist.", env_file.display());
        return Ok(());
    }
    let compose = compose_file(&board, options.compose.as_ref())
        .map_err(|e| format!("could not write the board's compose file: {e}"))?;
    let tool = detect_compose().await?;
    let command: &[&str] = if options.volumes {
        &["down", "--volumes"]
    } else {
        &["down"]
    };
    run_compose(tool, &env_file, &compose, command).await
}

pub async fn status() {
    let client = http_client();
    let board_url = std::env::var("PREPCOOK_SHARED_API_BASE")
        .ok()
        .filter(|v| !v.trim().is_empty())
        .unwrap_or_else(|| BOARD_URL.to_string());
    let board_url = board_url.trim_end_matches('/');
    let board_up = answers(&client, &format!("{board_url}/v1/health")).await;
    if board_up {
        println!("board:  up at {board_url}");
    } else {
        println!("board:  not answering at {board_url}");
    }

    match read_port_info("prepcook").await {
        Ok(info) => {
            let url = format!("http://127.0.0.1:{}", info.main_port);
            if answers(&client, &format!("{url}/api/health")).await {
                println!("server: running on port {} ({url})", info.main_port);
            } else {
                println!("server: not running (last ran on port {})", info.main_port);
            }
        }
        Err(_) => println!("server: not running"),
    }

    let auth = if board_up {
        board_auth(&client, board_url).await
    } else {
        describe_board_auth(&BoardAuth::Unknown(
            "the board is not answering".to_string(),
        ))
    };
    println!("auth:   {auth}");
}

/// What an authenticated request to the board says about this machine's
/// board secret.
#[derive(Debug, Clone, PartialEq, Eq)]
enum BoardAuth {
    /// The board answered as its owner; holds the owner's email.
    Accepted(String),
    /// The board answered 401/403: the secret is not the board's.
    Refused {
        source: String,
    },
    NoSecret,
    /// The request failed for another reason; holds why.
    Unknown(String),
}

async fn board_auth(client: &reqwest::Client, board_url: &str) -> String {
    let Some((secret, source)) = board_secret::resolve(Some(board_url)) else {
        return describe_board_auth(&BoardAuth::NoSecret);
    };
    let outcome = match utils::jwt::mint_owner_token(
        secret.expose(),
        chrono::Utc::now(),
        utils::jwt::OWNER_TOKEN_TTL_SECONDS,
    ) {
        Err(e) => BoardAuth::Unknown(e.to_string()),
        Ok(token) => match client
            .get(format!("{board_url}/v1/identity"))
            .bearer_auth(token)
            .send()
            .await
        {
            Err(e) => BoardAuth::Unknown(e.to_string()),
            Ok(response) if response.status().is_success() => {
                match response.json::<serde_json::Value>().await {
                    Ok(body) => BoardAuth::Accepted(
                        body["email"].as_str().unwrap_or("the owner").to_string(),
                    ),
                    Err(e) => BoardAuth::Unknown(e.to_string()),
                }
            }
            Ok(response)
                if matches!(
                    response.status(),
                    reqwest::StatusCode::UNAUTHORIZED | reqwest::StatusCode::FORBIDDEN
                ) =>
            {
                BoardAuth::Refused {
                    source: source.to_string(),
                }
            }
            Ok(response) => BoardAuth::Unknown(format!("HTTP {}", response.status())),
        },
    };
    describe_board_auth(&outcome)
}

/// One line for `prepcook status` about the board secret; never the secret.
fn describe_board_auth(outcome: &BoardAuth) -> String {
    match outcome {
        BoardAuth::Accepted(email) => {
            format!("the board accepts this machine's secret (as {email})")
        }
        BoardAuth::Refused { source } => {
            format!("the board refuses the board secret from {source}")
        }
        BoardAuth::NoSecret => format!(
            "no board secret (run prepcook up, or set {BOARD_SECRET_NAME} for a board on another machine)"
        ),
        BoardAuth::Unknown(why) => format!("unknown ({why})"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn env_value<'a>(contents: &'a str, key: &str) -> &'a str {
        contents
            .lines()
            .find_map(|line| line.strip_prefix(&format!("{key}=")))
            .unwrap_or_else(|| panic!("{key} missing"))
    }

    #[test]
    fn the_release_compose_file_is_pinned_to_this_version() {
        assert_eq!(RELEASE_COMPOSE.matches(BOARD_IMAGE_LATEST).count(), 1);
        let compose = release_compose();
        assert!(!compose.contains(BOARD_IMAGE_LATEST));
        assert!(compose.contains(&format!(
            "image: {BOARD_IMAGE}:{}",
            env!("CARGO_PKG_VERSION")
        )));
        assert!(!compose.contains("build:"));
    }

    #[test]
    fn the_generated_env_holds_every_required_value() {
        let contents = generate_env();
        for key in ["DB_PASSWORD", "ELECTRIC_ROLE_PASSWORD"] {
            let value = env_value(&contents, key);
            assert_eq!(URL_SAFE_NO_PAD.decode(value).unwrap().len(), 32);
            assert!(
                value
                    .chars()
                    .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
            );
        }
        // The board validates the JWT secret as standard base64 of >= 32 bytes.
        let secret = env_value(&contents, "PREPCOOK_JWT_SECRET");
        assert_eq!(STANDARD.decode(secret).unwrap().len(), 32);
        assert_eq!(
            env_value(&contents, "PUBLIC_BASE_URL"),
            "http://localhost:4110"
        );
        assert!(!contents.contains("SELF_HOST_LOCAL_AUTH"));
        assert_ne!(env_value(&generate_env(), "PREPCOOK_JWT_SECRET"), secret);
    }

    #[test]
    fn the_env_file_is_created_once_and_private() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join(".env");

        assert!(ensure_env_file(&path).unwrap());
        let contents = std::fs::read_to_string(&path).unwrap();
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(&path).unwrap().permissions().mode();
            assert_eq!(mode & 0o777, 0o600);
        }

        assert!(!ensure_env_file(&path).unwrap());
        assert_eq!(std::fs::read_to_string(&path).unwrap(), contents);
    }

    #[test]
    fn the_board_secret_is_read_from_a_generated_env() {
        let contents = generate_env();
        assert_eq!(
            board_secret::env_file_value(&contents, board_secret::BOARD_ENV_SECRET_KEY).as_deref(),
            Some(env_value(&contents, "PREPCOOK_JWT_SECRET"))
        );
    }

    #[test]
    fn the_status_line_reports_the_board_auth_without_the_secret() {
        assert_eq!(
            describe_board_auth(&BoardAuth::Accepted("owner@localhost".into())),
            "the board accepts this machine's secret (as owner@localhost)"
        );
        assert!(describe_board_auth(&BoardAuth::NoSecret).starts_with("no board secret"));
        assert_eq!(
            describe_board_auth(&BoardAuth::Refused {
                source: "the PREPCOOK_BOARD_SECRET environment variable".into()
            }),
            "the board refuses the board secret from the PREPCOOK_BOARD_SECRET environment variable"
        );
    }

    #[test]
    fn compose_arguments() {
        let env = Path::new("/data/board/.env");
        let file = Path::new("/data/board/docker-compose.yml");
        let joined = |args: Vec<OsString>| {
            args.iter()
                .map(|a| a.to_string_lossy().into_owned())
                .collect::<Vec<_>>()
                .join(" ")
        };
        assert_eq!(
            joined(compose_args(ComposeTool::Plugin, env, file, &["up", "-d"])),
            "compose --project-name prepcook --env-file /data/board/.env -f /data/board/docker-compose.yml up -d"
        );
        assert_eq!(
            joined(compose_args(
                ComposeTool::Standalone,
                env,
                file,
                &["down", "--volumes"]
            )),
            "--project-name prepcook --env-file /data/board/.env -f /data/board/docker-compose.yml down --volumes"
        );
    }

    #[test]
    fn a_given_compose_file_is_used_as_is() {
        let dir = tempfile::tempdir().unwrap();
        let given = PathBuf::from("/src/crates/remote/docker-compose.yml");
        assert_eq!(compose_file(dir.path(), Some(&given)).unwrap(), given);
        assert!(!dir.path().join("docker-compose.yml").exists());

        let written = compose_file(dir.path(), None).unwrap();
        assert_eq!(std::fs::read_to_string(written).unwrap(), release_compose());
    }
}
