#!/usr/bin/env python3
"""Generates the prepcook-* skills from the playbooks in this checkout.

    python3 toolkit/generator/generate.py                       # writes toolkit/skills/
    python3 toolkit/generator/generate.py --check               # exits 1 if toolkit/skills/ is stale
    python3 toolkit/generator/generate.py --manifest path/to/.prepcook/scripts.toml

Each generated skill is:

    ---
    name: prepcook-rca
    description: "..."
    ---
    <!-- the generated note: source commit, playbook, profile -->

    <toolkit/generator/preambles/prepcook-rca.md, then preambles/_conventions.md,
     both hand-written>

    <the playbook text from crates/services/src/services/config/playbooks.rs,
     through the substitution table, cut at the skill's anchor, with the
     {{product.*}} placeholders filled from the manifest's [profile]>

    <a hand-written tail, for the skills that have one>

The two supporting skills (repro-harness, evergreen-comments) are copied from
assets/agent-skills through their own few rules. `prepcook-self-review` is written
by hand; the generator neither writes nor checks it.

The profile comes from docs/examples/scripts.toml (the "Pantry" example) unless
--manifest names another, so the committed skills are a worked example. The
note records the short SHA of the last commit that changed any input; --check
ignores that SHA, so a commit that edits a playbook and regenerates in one go
is not stale the moment it lands.
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from pathlib import Path

import playbooks
from substitutions import COPIED_FILES, COPIED_RULES, RULES, SKILLS, TAILS, Rule, Skill

HERE = Path(__file__).resolve().parent
TOOLKIT = HERE.parent
REPO = playbooks.REPO
PREAMBLES = HERE / "preambles"
SKILLS_OUT = TOOLKIT / "skills"

# Skills in toolkit/skills/ that the generator neither writes nor checks.
HAND_MAINTAINED = ["prepcook-self-review"]

GENERATED_NOTE = (
    "<!-- Generated by toolkit/generator/generate.py from Prepcook at {sha} ({source}; "
    "product profile \"{profile}\" from {manifest}). Edit freely: a good edit is a proposal — open a pull "
    "request, and once it becomes a playbook change the next regeneration carries it. A regeneration "
    "overwrites this file. -->\n"
)
SHA_IN_NOTE = re.compile(r"(generate\.py from Prepcook at )\S+")

PROFILE_KEYS = ["name", "summary", "areas", "error_patterns", "evidence_tools"]
UNNAMED_PRODUCT = "this project"

# What `{{product.evidence_tools}}` ends with whenever it is not empty
# (`evidence::HARNESS_FALLBACK`).
HARNESS_FALLBACK = "If none of these show the failure, the harness is your evidence."
LOG_FILES = "Log files"


# --------------------------------------------------------------- profile


def load_profile(manifest: Path) -> dict[str, str]:
    """The `{{product.*}}` values from a manifest's `[profile]`, joined the way
    the orchestrator joins them (lists comma-separated), with the evidence
    placeholders rendered from its `[[profile.evidence]]`."""
    try:
        import tomllib
    except ModuleNotFoundError:  # Python < 3.11
        sys.exit("generate.py needs Python 3.11 or later (tomllib) to read the manifest")
    profile = tomllib.loads(manifest.read_text()).get("profile", {})
    values = {}
    for key in PROFILE_KEYS:
        value = profile.get(key, "")
        values[f"product.{key}"] = ", ".join(value) if isinstance(value, list) else str(value)
    if not values["product.name"].strip():
        values["product.name"] = UNNAMED_PRODUCT
    sources = [log_files_source(entry) for entry in profile.get("evidence", [])]
    values["product.evidence_tools"] = evidence_tools(
        [describe for _, describe in sources], values["product.evidence_tools"]
    )
    values["product.evidence_sources"] = "\n".join(f"- {label}" for label, _ in sources)
    return values


# --------------------------------------------------------------- evidence
#
# The orchestrator renders these in Rust (`services::evidence`); a test there
# (`the_toolkit_skills_carry_the_orchestrators_evidence_text`) fails when the
# committed skills stop matching it, so a change to either side shows up.


def log_files_source(entry: dict) -> tuple[str, str]:
    """(label, paragraph) for one `[[profile.evidence]]` entry, as
    `evidence::log_files::describe_paths` writes it. A manifest names only
    log_files sources; the orchestrator refuses any other kind."""
    if entry.get("kind") != "log_files":
        sys.exit(f"[[profile.evidence]] kind {entry.get('kind')!r}: a manifest names only log_files sources")
    raw = entry.get("paths", [])
    items = raw if isinstance(raw, list) else re.split(r"[\n,]", raw)
    paths = [path.strip() for path in items if path.strip()]
    label = str(entry.get("label", "")).strip() or LOG_FILES
    heading = label if label == LOG_FILES else f"{label} ({LOG_FILES})"
    shown = ", ".join(f"`{path}`" for path in paths)
    relative = ", relative to the worktree" if any(not path.startswith("/") for path in paths) else ""
    pronoun = "it" if len(paths) == 1 and not any(c in paths[0] for c in "*?[{") else "them"
    text = (
        f"{heading}: {shown}{relative}. Read {pronoun} with tail, grep or jq, or call "
        f"`evidence_search` with source \"{label}\": it returns the lines that contain the "
        "pattern, ignoring case, leaving out a line whose timestamp falls outside the window and "
        "keeping one that has none. Look for the failing request and the error logged after it, "
        "around the time you ran the harness."
    )
    notes = str(entry.get("notes", "")).strip()
    if notes:
        text += " " + (notes if notes.endswith((".", "!", "?")) else notes + ".")
    return label, text


def evidence_tools(paragraphs: list[str], appendix: str) -> str:
    """`{{product.evidence_tools}}`: the sources' paragraphs, the profile's
    `evidence_tools`, then the harness sentence; empty when there is neither."""
    parts = [paragraph.strip() for paragraph in paragraphs]
    if appendix.strip():
        parts.append(appendix.strip())
    if not parts:
        return ""
    return "\n\n".join(parts + [HARNESS_FALLBACK])


def render_profile(text: str, values: dict[str, str]) -> str:
    """`{{#if name}}…{{else}}…{{/if}}` and `{{name}}` for the product values, as
    `services::playbook_context::render_playbook` does it. Other placeholders
    are left alone; the substitution table has already replaced them."""
    out, rest = [], text
    while (start := rest.find("{{#if ")) != -1:
        name_end = rest.find("}}", start)
        close = rest.find("{{/if}}", name_end)
        if name_end == -1 or close == -1:
            break
        name = rest[start + len("{{#if "):name_end].strip()
        inner = rest[name_end + 2:close]
        then, _, otherwise = inner.partition("{{else}}")
        out.append(rest[:start])
        out.append(then if values.get(name, "").strip() else otherwise)
        rest = rest[close + len("{{/if}}"):]
    text = "".join(out) + rest
    for name, value in values.items():
        text = text.replace("{{" + name + "}}", value)
    return text


# ------------------------------------------------------------- the table


def apply(text: str, rules: list[Rule], target: str) -> str:
    for rule in rules:
        if rule.target == target:
            text = text.replace(rule.old, rule.new)
    return text


def cut(text: str, skill: Skill) -> str:
    if skill.side == "all":
        return text
    index = text.index(skill.anchor)
    return text[:index].rstrip() + "\n" if skill.side == "before" else text[index:]


def build(source: dict[str, str], profile: dict[str, str]) -> dict[str, str]:
    """Skill name → generated body (no frontmatter, no note, no preamble)."""
    rewritten = {name: apply(text, RULES, name) for name, text in source.items()}
    bodies = {}
    for skill in SKILLS:
        body = apply(cut(rewritten[skill.playbook], skill), RULES, skill.name)
        if skill.name in TAILS:
            body = body.rstrip() + "\n\n" + TAILS[skill.name] + "\n"
        bodies[skill.name] = render_profile(body, profile)
    return bodies


# --------------------------------------------------------------- output


def note(source: str, sha: str, profile: dict[str, str], manifest: str) -> str:
    return GENERATED_NOTE.format(sha=sha, source=source, profile=profile["product.name"], manifest=manifest)


def render(skill: Skill, body: str, stamp: str) -> str:
    # The skill's own preamble, then the conventions every generated skill shares.
    parts = [PREAMBLES / f"{skill.name}.md", PREAMBLES / "_conventions.md"]
    preamble = "".join(path.read_text().rstrip() + "\n\n" for path in parts if path.exists())
    return (
        f"---\nname: {skill.name}\ndescription: {json.dumps(skill.description, ensure_ascii=False)}\n---\n"
        + stamp
        + "\n"
        + preamble
        + body.rstrip()
        + "\n"
    )


def render_copied(name: str, file: str, text: str, stamp: str) -> str:
    text = apply(text, COPIED_RULES, f"{name}/{file}")
    if file != "SKILL.md":
        return text  # code and data files carry no note; the SKILL.md beside them does
    # Keep the skill's own frontmatter first; the note goes right after it.
    if text.startswith("---"):
        end = text.index("\n---", 3) + len("\n---\n")
        return text[:end] + stamp + text[end:]
    return stamp + text


def input_paths(manifest: Path) -> list[str]:
    paths = [playbooks.PLAYBOOKS_FILE, playbooks.SKILLS_DIR]
    try:
        paths.append(str(manifest.resolve().relative_to(REPO)))
    except ValueError:
        pass  # a manifest outside this checkout has no history here
    return paths


def display_path(manifest: Path) -> str:
    try:
        return str(manifest.resolve().relative_to(REPO))
    except ValueError:
        return str(manifest)


def generate(manifest: Path) -> dict[Path, str]:
    """Output path relative to toolkit/ → content."""
    profile = load_profile(manifest)
    sha = playbooks.source_sha(input_paths(manifest))
    shown = display_path(manifest)
    bodies = build(playbooks.load(), profile)
    files = {}
    for skill in SKILLS:
        stamp = note(f"{skill.playbook} playbook", sha, profile, shown)
        files[Path("skills") / skill.name / "SKILL.md"] = render(skill, bodies[skill.name], stamp)
    for name, names in COPIED_FILES.items():
        stamp = note(f"{playbooks.SKILLS_DIR}/{name}", sha, profile, shown)
        for file in names:
            files[Path("skills") / name / file] = render_copied(name, file, playbooks.load_skill(name, file), stamp)
    return files


def without_sha(text: str) -> str:
    return SHA_IN_NOTE.sub(r"\1<sha>", text)


def stale_files(files: dict[Path, str]) -> list[tuple[Path, str, str]]:
    """(path, committed, generated) for every file that differs from a fresh
    generation, ignoring the SHA in the note — plus any file under skills/
    the generator would not write (a renamed skill left behind)."""
    stale = []
    for rel, content in files.items():
        path = TOOLKIT / rel
        current = path.read_text() if path.exists() else ""
        if without_sha(current) != without_sha(content):
            stale.append((rel, current, content))
    hand = {SKILLS_OUT / name for name in HAND_MAINTAINED}
    for path in sorted(SKILLS_OUT.rglob("*")):
        rel = path.relative_to(TOOLKIT)
        if path.is_file() and rel not in files and not any(h in path.parents for h in hand):
            stale.append((rel, path.read_text(errors="replace"), ""))
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--manifest", type=Path, default=REPO / playbooks.DEFAULT_MANIFEST,
        help="the .prepcook/scripts.toml whose [profile] fills {{product.*}} (default: %(default)s)",
    )
    parser.add_argument("--check", action="store_true", help="diff against toolkit/skills/ instead of writing")
    args = parser.parse_args()

    files = generate(args.manifest)
    if args.check:
        stale = stale_files(files)
        for rel, current, content in stale:
            sys.stdout.writelines(
                difflib.unified_diff(
                    current.splitlines(True), content.splitlines(True), f"{rel} (committed)", f"{rel} (generated)"
                )
            )
        print(f"{'stale' if stale else 'current'}: {len(stale)} of {len(files)} files differ from a fresh generation")
        if stale:
            print("run `python3 toolkit/generator/generate.py` and commit toolkit/skills/")
        return 1 if stale else 0

    for rel, content in files.items():
        path = TOOLKIT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote toolkit/{rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
